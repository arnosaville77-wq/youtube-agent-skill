<?php
/**
 * Google AdSense: head script, manual ad slots, Auto Ads and ads.txt.
 *
 * Policy safeguards:
 * - The AdSense script is printed once, in <head>, only on pages that may show ads.
 * - No ads on 404 pages, empty search results, privacy / contact / terms / disclaimer pages.
 * - Every slot reserves its height (no CLS), is labelled «إعلان» and is
 *   separated from clickable elements by margins (see the theme CSS).
 *
 * @package SportsArena\Core
 */

namespace SportsArena\Core\Ads;

use SportsArena\Core\Options;
use SportsArena\Core\Pages;

defined( 'ABSPATH' ) || exit;

/**
 * Ads.
 */
final class Ads {

	const ADS_TXT_MARKER = '# Generated by SportsArena Core';

	/**
	 * Hook into WordPress.
	 *
	 * @return void
	 */
	public function register_hooks() {
		add_action( 'wp_enqueue_scripts', array( $this, 'head_script' ) );
		add_filter( 'script_loader_tag', array( $this, 'script_attributes' ), 10, 2 );
		add_filter( 'the_content', array( $this, 'in_article' ), 30 );
		add_action( 'init', array( $this, 'rewrite' ) );
		add_filter( 'query_vars', array( $this, 'query_vars' ) );
		add_action( 'template_redirect', array( $this, 'serve_ads_txt' ), 0 );
		add_action( 'update_option_' . Options::ADS, array( self::class, 'write_ads_txt' ) );
		add_action( 'add_option_' . Options::ADS, array( self::class, 'write_ads_txt' ) );
		add_filter( 'redirect_canonical', array( $this, 'no_trailing_slash_ads_txt' ) );
	}

	/**
	 * Validated publisher id ("ca-pub-1234567890123456") or ''.
	 *
	 * @return string
	 */
	public static function publisher_id() {
		$id = trim( (string) ( Options::ads()['publisher_id'] ?? '' ) );
		return preg_match( '/^ca-pub-\d{10,20}$/', $id ) ? $id : '';
	}

	/**
	 * Whether ads may be shown on the current page.
	 *
	 * @return bool
	 */
	public static function allowed() {
		$allowed = true;
		if ( is_404() || is_preview() || is_customize_preview() ) {
			$allowed = false;
		} elseif ( is_search() && ! have_posts() ) {
			$allowed = false;
		} elseif ( is_page() ) {
			$pages    = Pages::ids();
			$excluded = array_filter( array( $pages['privacy'] ?? 0, $pages['contact'] ?? 0, $pages['terms'] ?? 0, $pages['disclaimer'] ?? 0, (int) get_option( 'wp_page_for_privacy_policy' ) ) );
			if ( in_array( get_queried_object_id(), array_map( 'intval', $excluded ), true ) ) {
				$allowed = false;
			}
		}

		/**
		 * Filter whether ads can appear on the current request.
		 *
		 * @param bool $allowed Allowed.
		 */
		return (bool) apply_filters( 'sportsarena_ads_allowed', $allowed );
	}

	/**
	 * Enqueue the AdSense loader once (in <head>).
	 *
	 * @return void
	 */
	public function head_script() {
		$publisher = self::publisher_id();
		if ( ! $publisher || ! self::allowed() ) {
			return;
		}
		$settings = Options::ads();
		$has_slot = ! empty( $settings['auto_ads'] );
		foreach ( (array) $settings['slots'] as $slot ) {
			$has_slot = $has_slot || ! empty( $slot['enabled'] );
		}
		if ( ! $has_slot ) {
			return;
		}
		// Printed in <head> (wp_print_head_scripts) after the Consent Mode defaults.
		wp_enqueue_script(
			'sportsarena-adsense',
			'https://pagead2.googlesyndication.com/pagead/js/adsbygoogle.js?client=' . rawurlencode( $publisher ),
			array(),
			null, // phpcs:ignore WordPress.WP.EnqueuedResourceParameters.MissingVersion -- Google controls the version; a ?ver= would break caching rules.
			array(
				'strategy'  => 'async',
				'in_footer' => false,
			)
		);
	}

	/**
	 * Add crossorigin="anonymous" to the AdSense tag (as Google's snippet does).
	 *
	 * @param string $tag    Script tag.
	 * @param string $handle Handle.
	 * @return string
	 */
	public function script_attributes( $tag, $handle ) {
		if ( 'sportsarena-adsense' === $handle && ! str_contains( $tag, 'crossorigin' ) ) {
			$tag = str_replace( '<script ', '<script crossorigin="anonymous" ', $tag );
		}
		return $tag;
	}

	/**
	 * Markup of an ad slot.
	 *
	 * @param string $slot Slot id.
	 * @return string
	 */
	public static function render( $slot ) {
		$definitions = Options::ad_slots();
		if ( ! isset( $definitions[ $slot ] ) || ! self::allowed() ) {
			return '';
		}
		$settings = Options::ads();
		if ( ! empty( $settings['auto_ads'] ) ) {
			return ''; // Auto Ads places the ads; manual slots are disabled.
		}
		$config = $settings['slots'][ $slot ] ?? array();
		if ( empty( $config['enabled'] ) ) {
			return '';
		}
		$publisher = self::publisher_id();
		$def       = $definitions[ $slot ];

		$inner = '';
		if ( ! empty( $config['html'] ) ) {
			// Raw code is only accepted from users with unfiltered_html (see settings sanitizer).
			$inner = (string) $config['html'];
		} elseif ( $publisher && preg_match( '/^\d{6,20}$/', (string) $config['slot_id'] ) ) {
			$inner = sprintf(
				'<ins class="adsbygoogle" style="display:block" data-ad-client="%1$s" data-ad-slot="%2$s" data-ad-format="%3$s" data-full-width-responsive="false"></ins><script>(adsbygoogle=window.adsbygoogle||[]).push({});</script>',
				esc_attr( $publisher ),
				esc_attr( $config['slot_id'] ),
				esc_attr( 'vertical' === $def['format'] ? 'vertical' : ( 'horizontal' === $def['format'] ? 'horizontal' : 'rectangle' ) )
			);
		} elseif ( current_user_can( 'manage_options' ) ) {
			// Admin-only placeholder so the layout can be checked before approval.
			$inner = '<div class="sa-ad__placeholder">' . esc_html( $def['label'] ) . '</div>';
		}
		if ( '' === $inner ) {
			return '';
		}

		return sprintf(
			'<aside class="sa-ad sa-ad--%1$s" style="--sa-ad-h:%2$dpx;--sa-ad-h-lg:%3$dpx" aria-label="%4$s"><span class="sa-ad__label">%4$s</span><div class="sa-ad__slot">%5$s</div></aside>',
			esc_attr( str_replace( '_', '-', $slot ) ),
			(int) $def['mobile'],
			(int) $def['desktop'],
			esc_attr__( 'إعلان', 'sportsarena-core' ),
			$inner
		);
	}

	/**
	 * Insert the in-article slot after the second paragraph of single posts.
	 *
	 * @param string $content Content.
	 * @return string
	 */
	public function in_article( $content ) {
		if ( ! is_singular( 'post' ) || ! in_the_loop() || ! is_main_query() ) {
			return $content;
		}
		$ad = self::render( 'in_article' );
		if ( '' === $ad ) {
			return $content;
		}
		$offset = 0;
		for ( $i = 0; $i < 2; $i++ ) {
			$found = strpos( $content, '</p>', $offset );
			if ( false === $found ) {
				return $content;
			}
			$offset = $found + 4;
		}
		// Only when at least one more paragraph follows (never at the very end).
		if ( false === strpos( $content, '</p>', $offset ) ) {
			return $content;
		}
		return substr_replace( $content, $ad, $offset, 0 );
	}

	/**
	 * Content of ads.txt.
	 *
	 * @return string
	 */
	public static function ads_txt() {
		$publisher = self::publisher_id();
		if ( ! $publisher ) {
			return '';
		}
		return self::ADS_TXT_MARKER . "\ngoogle.com, " . str_replace( 'ca-', '', $publisher ) . ", DIRECT, f08c47fec0942fa0\n";
	}

	/**
	 * Rewrite: /ads.txt served dynamically when no physical file exists.
	 *
	 * @return void
	 */
	public function rewrite() {
		add_rewrite_rule( '^ads\.txt$', 'index.php?sa_ads_txt=1', 'top' );
	}

	/**
	 * Query vars.
	 *
	 * @param string[] $vars Vars.
	 * @return string[]
	 */
	public function query_vars( $vars ) {
		$vars[] = 'sa_ads_txt';
		return $vars;
	}

	/**
	 * Avoid /ads.txt/ redirects.
	 *
	 * @param string|false $redirect Redirect URL.
	 * @return string|false
	 */
	public function no_trailing_slash_ads_txt( $redirect ) {
		return get_query_var( 'sa_ads_txt' ) ? false : $redirect;
	}

	/**
	 * Serve ads.txt.
	 *
	 * @return void
	 */
	public function serve_ads_txt() {
		if ( ! get_query_var( 'sa_ads_txt' ) ) {
			return;
		}
		$settings = Options::ads();
		$content  = ! empty( $settings['ads_txt'] ) ? self::ads_txt() : '';
		if ( '' === $content ) {
			status_header( 404 );
			exit;
		}
		status_header( 200 );
		header( 'Content-Type: text/plain; charset=UTF-8' );
		header( 'X-Robots-Tag: noindex', true );
		echo esc_html( $content );
		exit;
	}

	/**
	 * Write a physical ads.txt in the site root when possible. A file that
	 * was not generated by this plugin is never overwritten.
	 *
	 * @return void
	 */
	public static function write_ads_txt() {
		$settings = Options::ads();
		$content  = ! empty( $settings['ads_txt'] ) ? self::ads_txt() : '';
		$path     = trailingslashit( ABSPATH ) . 'ads.txt';

		require_once ABSPATH . 'wp-admin/includes/file.php';
		if ( 'direct' !== get_filesystem_method( array(), ABSPATH ) || ! WP_Filesystem() ) {
			return; // The dynamic /ads.txt route still works.
		}
		global $wp_filesystem;

		if ( $wp_filesystem->exists( $path ) ) {
			$current = (string) $wp_filesystem->get_contents( $path );
			if ( ! str_starts_with( $current, self::ADS_TXT_MARKER ) ) {
				return; // Not ours.
			}
			if ( '' === $content ) {
				$wp_filesystem->delete( $path );
				return;
			}
		}
		if ( '' !== $content ) {
			$wp_filesystem->put_contents( $path, $content, FS_CHMOD_FILE );
		}
	}
}
